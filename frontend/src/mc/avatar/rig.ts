/**
 * Q 版人物的骨架尺寸（全场景共用）。仍是 8 根骨头：0 脚底、1 髋、2 上半身、3 头、4 右臂、5 左臂、6 右腿、7 左腿，
 * 膝盖以下的小腿和鞋是挂在腿骨上的子网格（坐下时代码把它折回竖直）。
 *
 * 单位 T = 1/48 米，也是贴图的 1 个像素（每米 48 像素）。
 *   头 36×36×30 T（整颗头再放大 HEAD_SCALE=1.1 倍：贴图仍按 36 画，头上 1 像素 ≈ 1.1 T）；躯干 18×17×10；
 *   大腿 10 + 小腿 28（含鞋 6）；腿宽 9（两腿并拢、粗短）；胳膊 7×17×7。
 *   身高（不含头发）55 + 39.6 ≈ 94.6 T ≈ 1.97 米，头 : 身 = 39.6 : 55 ≈ 1 : 1.39。
 *
 * 为什么小腿这么长：统一座面高 0.50 米（SEAT_H），坐下时大腿水平、下沿贴座面，膝轴在座面上方半个腿厚（4 T），
 * 小腿竖直垂下要正好够到地面，所以膝轴到脚底 = 24 + 4 = 28 T。旧的 Q 版骨架腿总长只有 24 T（=座高），
 * 坐下脚离地 0.31 米，只能踩脚踏；现在脚底平踩在地上。坐姿眼高（EYE_SIT）和旧骨架基本一样（0.72 / 0.77），
 * 站着变高（和最早的方块人 1.875 米相当，房间、门、镜头本来就是按这个高度搭的）。
 */
export const T=1/48;
export const RIG={
  /** 腿：宽 9、深 8；髋轴到膝 10，膝到脚底 28（含鞋 6） */
  leg:{w:9,d:8,thigh:10,shin:28,shoe:6,x:4.5},
  /** 躯干：宽 18、高 17、深 10，从髋（38）到肩线（55） */
  torso:{w:18,h:17,d:10},
  /** 胳膊：7×17×7，肩轴在躯干顶下 2 T，x=±12.5 */
  arm:{w:7,h:17,d:7,x:12.5,drop:2},
  /** 头：36 宽、36 高、30 深，颈轴在躯干顶（侧面浅一点，不像一只方箱子） */
  head:{w:36,h:36,d:30},
  /** 脸上眼睛中心离头底 13.5 T（贴图第 18–26 行） */
  eyeY:13.5,
};
export const HIP_Y=RIG.leg.thigh+RIG.leg.shin;            // 38
export const NECK_Y=HIP_Y+RIG.torso.h;                   // 55
/** 头的整体放大倍数（骨骼缩放，挂在头骨上的头发、帽子、眼镜一起放大） */
export const HEAD_SCALE=1.1;
export const HEAD_TOP=NECK_Y+RIG.head.h*HEAD_SCALE;      // 94.6
/**
 * 头部局部坐标的几个面：左右半宽、前后半深（脸在 +z）。脸那一面两侧的竖棱切掉 2 T（脸板 fx=±16、头的两侧面到 hz-2 为止），
 * 斜着、侧着看头不是一只方箱子，脸颊到侧面有一道转折。
 */
export const HEAD={hx:RIG.head.w/2,hz:RIG.head.d/2,h:RIG.head.h,fx:RIG.head.w/2-2,cut:2};
/** 统一座面高（地面以上，米）。所有新椅子的座面顶都在这里。 */
export const SEAT_H=.5;
/** 坐下时根点比座位锚点（座面顶）低多少：髋轴要在座面上方半个腿厚，根点 = 锚点 - (髋高 - 半腿厚)。34 T ≈ 0.708 */
export const SIT_DROP=(HIP_Y-RIG.leg.d/2)*T;
/** 坐下时大腿、小腿的转角：大腿水平（-90°），小腿竖直（膝盖 +90°），鞋底正好落在地面上。 */
export const SIT_THIGH=-Math.PI/2,SIT_KNEE=Math.PI/2;
/** 站立眼高（脚底以上）：55 + 13.5×1.1 ≈ 69.9 T ≈ 1.456 */
export const EYE_STAND=(NECK_Y+RIG.eyeY*HEAD_SCALE)*T;
/** 坐姿眼高（座位锚点以上）：≈ 35.9 T ≈ 0.747 */
export const EYE_SIT=EYE_STAND-SIT_DROP;
/** 手里拿东西 / 碰道具的那一点（胳膊骨骼空间，肩轴往下到手心）：-15 T */
export const HAND_REACH=-(RIG.arm.h-RIG.arm.drop)*T;
/** 名字牌在眼睛上方多高：盖过头顶、头发和帽子（头顶以上 10 T） */
export const LABEL_ABOVE_EYE=((RIG.head.h-RIG.eyeY)*HEAD_SCALE+10)*T;
